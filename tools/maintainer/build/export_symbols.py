#!/usr/bin/env python3
"""Convert the .erx.lib export registry of the main program into a symbol table for the decomp project.

Background: SLUS_217.88 is fully stripped (.mdebug=0, no .symtab). 99.3 percent
of its 10,951 functions are FUN_*. The .erx.lib file is an export registry with
21 libraries, 1,109 slots, and 749 unique function addresses. This script
converts it into a symbol table. Each of the 749 functions gets at least a
"library and slot" name as the start point for manual naming.

Input: out/evidence/hle_tables_SLUS.txt (written by tools/research/imports.py).
This path is a private-side evidence input. Keep the name.
Output:
  out/evidence/erx_symbols.tsv   address, primary name, all aliases, Ghidra function entry flag
  out/evidence/symbols.txt       decomp project style: `<addr_hex> <name>` (primary name)

Usage: python3 tools/maintainer/build/export_symbols.py

把主程序 .erx.lib 导出注册表转成 decomp 项目可用的符号表。
SLUS_217.88 被完全 strip，10,951 个函数里 99.3% 是 FUN_*；
.erx.lib 是一张导出注册表（21 个库 / 1,109 个槽位 / 749 个唯一函数地址）。
输入 out/evidence/** 与 out/ghidra/** 属私有侧证据，路径保留不改。
"""
import re, os, json, collections

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLES = os.path.join(BASE, 'out/evidence/hle_tables_SLUS.txt')
FUNCS = os.path.join(BASE, 'out/ghidra/SLUS_217.88.functions.tsv')
OUT_TSV = os.path.join(BASE, 'out/evidence/erx_symbols.tsv')
OUT_SYM = os.path.join(BASE, 'out/evidence/symbols.txt')

# These libraries are the API that the game itself exports. Give them a more
# visible prefix during manual naming.
GAME_LIBS = {'baseelf'}


def parse_tables(path):
    """Return [(lib, slot, addr, kind)] and skip none slots.

    返回 [(lib, slot, addr, kind)]，跳过 none 槽位。
    """
    libs = []
    cur = None
    for line in open(path, encoding='utf-8'):
        m = re.match(r'^=== library (\S+)\s+version=(\S+)\s+slots=(\d+)', line)
        if m:
            cur = m.group(1)
            continue
        m = re.match(r'^\s+(\d+)\s+(0x[0-9a-f]+)\s+(\S+)', line)
        if m and cur is not None:
            slot, addr, kind = int(m.group(1)), int(m.group(2), 16), m.group(3)
            if kind != 'none':
                libs.append((cur, slot, addr, kind))
    return libs


def parse_func_entries(path):
    s = set()
    if not os.path.exists(path):
        return s
    for line in open(path, encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) >= 3 and p[0] != 'addr':
            try:
                s.add(int(p[0], 16))
            except ValueError:
                pass
    return s


def main():
    rows = parse_tables(TABLES)
    entries = parse_func_entries(FUNCS)

    by_addr = collections.OrderedDict()
    for lib, slot, addr, kind in rows:
        by_addr.setdefault(addr, []).append((lib, slot, kind))

    def primary(addr):
        """Select the primary name. The game API wins. Then sort by (library, slot) and take the first.

        选主名：游戏自身 API 优先，其次按 (库名, 槽号) 排序取第一个。
        """
        owners = by_addr[addr]
        game = [o for o in owners if o[0] in GAME_LIBS]
        pick = (game or sorted(owners))[0]
        return pick[0], pick[1]

    os.makedirs(os.path.dirname(OUT_TSV), exist_ok=True)
    with open(OUT_TSV, 'w', encoding='utf-8') as f:
        f.write('addr\tslot\tprimary_name\tis_func_entry\tn_aliases\taliases\n')
        for addr in sorted(by_addr):
            lib, slot = primary(addr)
            aliases = ';'.join('%s:%d' % (l, s) for l, s, _ in sorted(by_addr[addr]))
            f.write('0x%08x\t%d\t%s_%d\t%s\t%d\t%s\n' % (
                addr, slot, lib, slot, 'yes' if addr in entries else 'no',
                len(by_addr[addr]), aliases))

    with open(OUT_SYM, 'w', encoding='utf-8') as f:
        f.write('# Generated by tools/maintainer/build/export_symbols.py. Source: the .erx.lib export registry of the main program.\n')
        f.write('# Format: <vaddr_hex> <name>   (the primary name wins; see erx_symbols.tsv for the aliases)\n')
        for addr in sorted(by_addr):
            lib, slot = primary(addr)
            f.write('0x%08x %s_%d\n' % (addr, lib, slot))

    # ---- statistics ----
    stats = collections.Counter()
    for lib, slot, addr, kind in rows:
        stats[lib] += 1
    print('slots read          = %d' % len(rows))
    print('unique addresses    = %d' % len(by_addr))
    print('  of which Ghidra function entries = %d' % sum(1 for a in by_addr if a in entries))
    print('libraries           = %d' % len(stats))
    print()
    print('--- top 10 libraries by unique address count ---')
    per = collections.Counter()
    seen = set()
    for lib, slot, addr, kind in sorted(rows):
        if (lib, addr) not in seen:
            seen.add((lib, addr)); per[lib] += 1
    for lib, n in per.most_common(10):
        print('  %-16s %d' % (lib, n))
    print()
    print('wrote:')
    print('  %s' % os.path.relpath(OUT_TSV, BASE))
    print('  %s' % os.path.relpath(OUT_SYM, BASE))


if __name__ == '__main__':
    main()
