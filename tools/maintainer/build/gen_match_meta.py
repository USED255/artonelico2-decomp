#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build config/match_meta.tsv. This file is the machine-readable ledger of symbols with C code.

Why the file exists:
  * `matched_symbols.txt` is the only build switch. It holds one line per
    symbol: `<symbol> [<source>] # <comment>`.
  * The long-term plan (private repository note R11) needs a traceable entry
    for each matched symbol: source file, compile flags, difficulty class,
    batch, and evidence. Each matcher writes its own section. This ledger
    collects all sections in one file.

Inputs. All inputs exist already. The script collects data only. It does not
guess.
  * routebjp/config/matched_symbols.txt  -- symbol, source basename, section
  * routebjp/config/source_flags.tsv     -- extra compile flags for one source
  * out/evidence/jp_m3_workqueue.tsv     -- difficulty category (class column)
    Private pipeline compatibility, do not rename: the file name
    jp_m3_workqueue.tsv and the private-side path out/evidence/**.

Output: `config/match_meta.tsv`
  sym  src  flags  class  batch  evidence

Usage: python3 tools/maintainer/build/gen_match_meta.py [--check]
       --check compares the current ledger with the source of truth. It writes
       nothing. Use it in CI and at the end of a batch.

生成 config/match_meta.tsv，这是「已 C 化符号」的机器可读来源台账。

为什么要它：`matched_symbols.txt` 是构建唯一开关，只有「符号 [源] # 注释」；
长期计划（私有仓库记录 R11）要求每个已匹配符号能追溯源文件、编译标志、
难度类别、批次与证据。多个匹配器各写自己的段，由本台账统一汇总。

数据来源（全部已存在，本脚本只做汇总，不猜测）：私有侧输入，
包括 routebjp/config/matched_symbols.txt、routebjp/config/source_flags.tsv
与 out/evidence/jp_m3_workqueue.tsv（难度 class 列）。
私有流水线兼容，勿改名：jp_m3_workqueue.tsv 文件名与 out/evidence/** 私有侧路径。

产出 config/match_meta.tsv，列为 sym / src / flags / class / batch / evidence。
用法：python3 tools/maintainer/build/gen_match_meta.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools" / "project"))
from at2_paths import (  # noqa: E402  layout-independent path resolution (MATCHED_LIST/FLAGS_TSV/WORKQUEUE)
    MATCHED_LIST as MATCHED,
    FLAGS_TSV as FLAGS,
    WORKQUEUE,
    PROJECT_ROOT,
)

OUT = PROJECT_ROOT / "config" / "match_meta.tsv"

# Section markers in matched_symbols.txt. These strings must equal the marker
# lines in that file. The private pipeline writes the same markers.
#
# matched_symbols.txt 里的段标记。常量必须与该文件的标记行逐字一致。
STUB_BEGIN = "# ---- matching batch: stubs (syscall/break/hand-written instructions; generated by auto_match_stub.py; do not edit this section) ----"
M3_BEGIN = "# ---- matching batch: trivial auto-match (generated by auto_match_trivial.py; do not edit this section) ----"
M2_MARKER = "per-function compare samples"


def parse_matched():
    """Return [(sym, src, tag, batch)].

    返回 [(sym, src, tag, batch)]。

    The batch values are private ledger values. Do not rename them.
    batch 取值是私有台账词汇，保持 M2 / M3 / stub 不变。
    """
    rows, batch = [], "?"
    for line in MATCHED.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if M2_MARKER in s:
            batch = "M2"
            continue
        if s.startswith(M3_BEGIN):
            batch = "M3"
            continue
        if s.startswith(STUB_BEGIN):
            batch = "stub"
            continue
        if s.startswith("#") or not s:
            continue
        body = line.split("#", 1)
        parts = body[0].split()
        if not parts:
            continue
        sym = parts[0]
        src = parts[1] if len(parts) > 1 else sym
        tag = body[1].strip().split()[0] if len(body) > 1 and body[1].strip() else ""
        rows.append((sym, src, tag, batch))
    return rows


def parse_flags():
    out = {}
    if not FLAGS.is_file():
        return out
    # Line 1 is the header row (source-basename<TAB>extra-cflags). Skip it.
    # 第 1 行是表头（source-basename<TAB>extra-cflags），跳过。
    for line in FLAGS.read_text(encoding="utf-8").splitlines()[1:]:
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        a = line.split()
        out[a[0]] = " ".join(a[1:])
    return out


def parse_class():
    out = {}
    if not WORKQUEUE.is_file():
        return out
    lines = WORKQUEUE.read_text(encoding="utf-8").splitlines()
    idx = {k: i for i, k in enumerate(lines[0].split("\t"))}
    if "class" not in idx:
        return out
    for line in lines[1:]:
        p = line.split("\t")
        if len(p) >= len(idx):
            out[p[idx["name"]]] = p[idx["class"]]
    return out


def build() -> str:
    flags, cls = parse_flags(), parse_class()
    lines = ["# Ledger of symbols with C code. tools/maintainer/build/gen_match_meta.py collects it. The source of truth is matched_symbols.txt and source_flags.tsv.",
             "# sym\tsrc\tflags\tclass\tbatch\tevidence"]
    for sym, src, tag, batch in parse_matched():
        evidence = "objdiff100+payload_check" + (f":{tag}" if tag else "")
        lines.append("\t".join([sym, src, flags.get(src, ""), cls.get(sym, ""), batch, evidence]))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="Check only; do not write")
    args = ap.parse_args()
    text = build()
    if args.check:
        if not OUT.is_file():
            print(f"FAIL: missing {OUT}")
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print(f"FAIL: {OUT} does not agree with the source of truth (run python3 tools/maintainer/build/gen_match_meta.py to regenerate)")
            return 1
        print(f"ok: {OUT.relative_to(ROOT)} agrees with the source of truth ({len(text.splitlines()) - 2} entries)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    n = len(text.splitlines()) - 2
    print(f"wrote {OUT.relative_to(ROOT)}: {n} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
