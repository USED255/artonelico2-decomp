#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Observe the shipped cc1's global allocation decisions (read-only, gdb).

Why this tool exists: the handbook's DIAGNOSTICS page says "ask the compiler". This
tool is the packaged version of that recipe, with the two traps this project hit:

1. `allocno_order` is freed at the end of `global_alloc`. A dump taken after the
   function returns can look plausible and be wrong. The order is therefore read at
   the **first `find_reg` call**, where `qsort` has finished and the array is alive.
2. `find_reg` returns nothing. The choice is a side effect written into
   `reg_renumber[allocno[num].reg]`; the two-step ladder calls it with
   `alt_regs_p=0` then `alt_regs_p=1`.

What it reports:

* the allocation order (`allocno_order`);
* every `find_reg` attempt (allocno, alt class flag, chosen register, or -1);
* the allocnos that got no register (the spill set);
* a cross-check against `-da`'s `;; Register dispositions:` (the compiler's own
  answer);
* with `--prefs`: preference edits made before ordering (expand/prune mask changes)
  and the preferences recorded by `set_preference` (effect-diff, not a replay).

The hook addresses are resolved from the cc1 on this machine by symbol, so the tool
follows a rebuilt compiler. Eight-byte entry guards are enforced only when the cc1
sha256 matches the build this handbook is pinned to; on any other build the tool
warns and resolves symbols by name instead of refusing to run.

Requirements: gdb on PATH (tested with 16.3) and the project's cc1 (not stripped,
carries DWARF). The tool observes the **compiler**, never the game binary.

Usage:

    python3 tools/compiler/ee-gcc-observe-alloc.py --src candidate.c --flags="-O2 -G0"
    python3 tools/compiler/ee-gcc-observe-alloc.py --src big.c --function func_001d4b88 \
        --include include --flags="-Os -fno-thread-jumps" --prefs
    python3 tools/compiler/ee-gcc-observe-alloc.py --selftest
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANCHOR = ROOT / "tools" / "compiler" / "ee-gcc-anchor.py"
DEFAULT_CC1 = Path.home() / "eecc" / "ee-gcc3.2-040921" / "lib" / "gcc-lib" / "ee" / "3.2-ee-040921" / "cc1"

# sha256 of the build this handbook is pinned to (VERIFY.md states the same hash).
PINNED_SHA256 = "0bcc90bd23e10698e75047db9a84ea47e753791115fdd23d6f637a544f6d257d"
FIRST_PSEUDO = 144  # L-EE-016: hard registers are numbered 0..143; 144 is the first pseudo.

# Eight-byte entry guards, valid for the pinned build only.
GUARDS = {
    "find_reg": "5589e557565381ec",
    "expand_function_start": "5589e557565383ec",
    "prune_preferences": "5589e557565381ec",
    "expand_preferences": "5589e557565381ec",
    "set_preference": "5589e557565383ec",
}

GDB_TEMPLATE = r'''# Generated by ee-gcc-observe-alloc.py -- read-only observation of the shipped cc1.
import gdb

ADDRS = __ADDRS__
GUARDS = __GUARDS__
ENFORCE_GUARDS = __ENFORCE__
GATE = __GATE__
WANT_PREFS = __WANT_PREFS__

first_pseudo = __FIRST_PSEUDO__
FAILURES = []
ARMED = {"on": GATE == ""}
ORDER_DONE = {"on": False}
CALLS = []
STATS = {"setpref": 0, "prune_changed": 0, "expand_changed": 0}

INF = gdb.selected_inferior()


def rb(addr, n):
    return INF.read_memory(addr, n).tobytes()


def u32(addr):
    return int.from_bytes(rb(addr, 4), "little")


def guard_ok(name, addr):
    if not ENFORCE_GUARDS:
        return True
    want = bytes.fromhex(GUARDS[name])
    got = rb(addr, len(want))
    if got != want:
        FAILURES.append((name, hex(addr), want.hex(), got.hex()))
        print("OA GUARD-FAIL %s @%s want=%s got=%s" % (name, hex(addr), want.hex(), got.hex()), flush=True)
        return False
    return True


def ae(expr):
    return gdb.parse_and_eval(expr)


def arg_int(off):
    try:
        return int(ae("*(int *)($esp + %d)" % off)) & 0xFFFFFFFF
    except gdb.error:
        return -1


def allocno_int(num, field):
    try:
        return int(ae("allocno[%d].%s" % (num, field)))
    except gdb.error:
        return -1


def max_allocno():
    try:
        return int(ae("max_allocno"))
    except gdb.error:
        return -1


def layout():
    base = int(ae("(char *)&allocno[0]"))
    offs = {}
    for f in ("hard_reg_preferences", "hard_reg_copy_preferences", "hard_reg_full_preferences"):
        offs[f] = int(ae("(char *)&allocno[0].%s - (char *)&allocno[0]" % f))
    size = int(ae("sizeof(struct allocno)"))
    return base, offs, size


def snapshot(maxa):
    base, offs, size = layout()
    if maxa <= 0:
        return []
    blob = rb(base, maxa * size)
    rows = []
    for i in range(maxa):
        row = {}
        for f, o in offs.items():
            row[f] = int.from_bytes(blob[i * size + o:i * size + o + 24], "little")
        rows.append(row)
    return rows


def changed_rows(before, after):
    out = []
    for i, (a, b) in enumerate(zip(before, after)):
        if any(a[f] != b[f] for f in a):
            out.append(i)
    return out


def decode_reg(rtx, depth=0):
    if rtx <= 0 or depth > 3:
        return None, False
    try:
        code = u32(rtx) & 0xFFFF
    except gdb.error:
        return None, False
    if code == 73:  # REG
        return u32(rtx + 4), depth > 0
    if code == 75:  # SUBREG
        r, _ = decode_reg(u32(rtx + 4), depth + 1)
        return r, True
    try:
        inner = u32(rtx + 4)
        c2 = u32(inner) & 0xFFFF
    except gdb.error:
        return None, False
    if 1 <= c2 <= 200:
        return decode_reg(inner, depth + 1)
    return None, False


def allocno_of(regno):
    try:
        return int(ae("((int *)reg_allocno)[%d]" % regno))
    except gdb.error:
        return -1


def masks_of(allocno):
    out = {}
    for f in ("hard_reg_preferences", "hard_reg_copy_preferences", "hard_reg_full_preferences"):
        out[f] = int(ae("allocno[%d].%s[0]" % (allocno, f))) | \
                 (int(ae("allocno[%d].%s[1]" % (allocno, f))) << 64) | \
                 (int(ae("allocno[%d].%s[2]" % (allocno, f))) << 128)
    return out


class FuncGate(gdb.Breakpoint):
    def __init__(self):
        super().__init__("*%d" % ADDRS["expand_function_start"], internal=True)

    def stop(self):
        if not guard_ok("expand_function_start", ADDRS["expand_function_start"]):
            gdb.execute("kill")
            return False
        try:
            decl = int(ae("*(unsigned int *)($esp + 4)"))
            name = ae("((struct tree_identifier *)((union tree_node *)"
                      "((struct tree_decl *)%d)->name))->id.str" % decl).string()
        except gdb.error:
            name = "?"
        ARMED["on"] = GATE == "" or name == GATE
        ORDER_DONE["on"] = False
        print("OA FUNC %s armed=%d" % (name, 1 if ARMED["on"] else 0), flush=True)
        return False


class FindRegReturn(gdb.Breakpoint):
    def __init__(self, addr):
        super().__init__("*%d" % addr, internal=True)
        self.addr = addr
        self.guard = rb(addr, 8)
        self.stack = []

    def stop(self):
        if rb(self.addr, 8) != self.guard:
            FAILURES.append(("ret@%s" % hex(self.addr), "changed", "", ""))
            print("OA RET-GUARD-FAIL @%s" % hex(self.addr), flush=True)
            return False
        if not self.stack:
            return False
        num = self.stack.pop()
        pseudo = allocno_int(num, "reg")
        try:
            chosen = int(ae("reg_renumber[%d]" % pseudo))
        except gdb.error:
            chosen = None
        print("OA OUT %d pseudo=%d chosen=%s" % (num, pseudo, chosen), flush=True)
        return False


class FindReg(gdb.Breakpoint):
    def __init__(self):
        super().__init__("*%d" % ADDRS["find_reg"], internal=True)
        self.ret = {}

    def stop(self):
        if not guard_ok("find_reg", ADDRS["find_reg"]):
            gdb.execute("kill")
            return False
        if not ARMED["on"]:
            return False
        num = arg_int(4)
        alt = arg_int(12)
        cc = arg_int(16)
        retry = arg_int(20)
        maxa = max_allocno()
        if not (0 <= num < maxa) or alt not in (0, 1) or cc not in (0, 1) or retry not in (0, 1):
            print("OA DECODE-FAIL num=%s alt=%s cc=%s retry=%s maxa=%s" % (num, alt, cc, retry, maxa), flush=True)
            gdb.execute("kill")
            return False
        if not ORDER_DONE["on"]:
            ORDER_DONE["on"] = True
            vals = []
            for i in range(maxa):
                try:
                    vals.append(int(ae("allocno_order[%d]" % i)))
                except gdb.error:
                    break
            print("OA ORDER %d %s" % (len(vals), ",".join(map(str, vals))), flush=True)
        try:
            ret = int(ae("*(unsigned int *)$esp"))
        except gdb.error:
            ret = 0
        if ret and ret not in self.ret:
            self.ret[ret] = FindRegReturn(ret)
        if ret:
            self.ret[ret].stack.append(num)
        print("OA IN %d alt=%d cc=%d retry=%d size=%d calls=%d nrefs=%d freq=%d live=%d"
              % (num, alt, cc, retry, allocno_int(num, "size"), allocno_int(num, "calls_crossed"),
                 allocno_int(num, "n_refs"), allocno_int(num, "freq"), allocno_int(num, "live_length")),
              flush=True)
        return False


class PrefReturn(gdb.Breakpoint):
    def __init__(self, addr, name):
        super().__init__("*%d" % addr, internal=True)
        self.addr = addr
        self.name = name
        self.guard = rb(addr, 8)
        self.stack = []

    def stop(self):
        if rb(self.addr, 8) != self.guard:
            print("OA RET-GUARD-FAIL %s @%s" % (self.name, hex(self.addr)), flush=True)
            return False
        if not self.stack:
            return False
        before = self.stack.pop()
        after = snapshot(max_allocno())
        changed = changed_rows(before, after)
        if self.name == "prune_preferences":
            STATS["prune_changed"] += len(changed)
        else:
            STATS["expand_changed"] += len(changed)
        print("OA PREF %s changed=%d" % (self.name, len(changed)), flush=True)
        return False


class PrefPhase(gdb.Breakpoint):
    def __init__(self, name):
        super().__init__("*%d" % ADDRS[name], internal=True)
        self.name = name
        self.addr = ADDRS[name]
        self.ret = {}

    def stop(self):
        if not guard_ok(self.name, self.addr):
            gdb.execute("kill")
            return False
        if not ARMED["on"] or not WANT_PREFS:
            return False
        maxa = max_allocno()
        try:
            ret = int(ae("*(unsigned int *)$esp"))
        except gdb.error:
            return False
        if not ret:
            return False
        if ret not in self.ret:
            self.ret[ret] = PrefReturn(ret, self.name)
        self.ret[ret].stack.append(snapshot(maxa))
        return False


class SetPrefReturn(gdb.Breakpoint):
    def __init__(self, addr):
        super().__init__("*%d" % addr, internal=True)
        self.addr = addr
        self.guard = rb(addr, 8)
        self.stack = []

    def stop(self):
        if rb(self.addr, 8) != self.guard:
            print("OA RET-GUARD-FAIL set_preference @%s" % hex(self.addr), flush=True)
            return False
        if not self.stack:
            return False
        ctx = self.stack.pop()
        for a in ctx["cands"]:
            after = masks_of(a)
            delta = 0
            for f in after:
                delta |= after[f] & ~ctx["before"][a][f]
            if delta:
                print("OA SETPREF %d %s dest=%d src=%d subreg=%d"
                      % (a, ",".join(str(b) for b in range(192) if (delta >> b) & 1),
                         ctx["dest"], ctx["src"], ctx["sub"]), flush=True)
        return False


class SetPref(gdb.Breakpoint):
    def __init__(self):
        super().__init__("*%d" % ADDRS["set_preference"], internal=True)
        self.ret = {}

    def stop(self):
        if not guard_ok("set_preference", ADDRS["set_preference"]):
            gdb.execute("kill")
            return False
        if not ARMED["on"] or not WANT_PREFS:
            return False
        esp = int(ae("$esp"))
        dest_raw, dsub = decode_reg(u32(esp + 4))
        src_raw, ssub = decode_reg(u32(esp + 8))
        if dest_raw is None or src_raw is None:
            return False
        ret = u32(esp)
        if ret not in self.ret:
            self.ret[ret] = SetPrefReturn(ret)
        cands = []
        for r in (dest_raw, src_raw):
            if r >= first_pseudo:
                a = allocno_of(r)
                if a >= 0 and a not in cands:
                    cands.append(a)
        self.ret[ret].stack.append(dict(cands=cands, before={a: masks_of(a) for a in cands},
                                        dest=dest_raw, src=src_raw, sub=bool(dsub or ssub)))
        STATS["setpref"] += 1
        return False


gdb.execute("set pagination off")
gdb.execute("set confirm off")
KEEP = [FuncGate(), FindReg()]  # keep references alive across the run
if WANT_PREFS:
    KEEP.append(PrefPhase("expand_preferences"))
    KEEP.append(PrefPhase("prune_preferences"))
    KEEP.append(SetPref())
try:
    gdb.execute("run")
except gdb.error as exc:
    print("OA RUN-ERROR %s" % str(exc)[:200], flush=True)
print("OA STATS setpref=%d expand_changed=%d prune_changed=%d" %
      (STATS["setpref"], STATS["expand_changed"], STATS["prune_changed"]), flush=True)
print("OA GUARD-FAILURES %d" % len(FAILURES), flush=True)
'''


def fail(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def resolve_symbol(cc1: Path, name: str, source_hint: str | None = None) -> tuple[int, str]:
    """Resolve a symbol to (address, source) with the handbook's anchor tool."""
    out = subprocess.run([sys.executable, str(ANCHOR), "--cc1", str(cc1), "symbol", name],
                         capture_output=True, text=True, cwd=ROOT)
    hits = []
    for line in out.stdout.splitlines():
        m = re.search(r"@\s*0x([0-9a-fA-F]+)\s*(?:->|→)\s*(\S+)", line)
        if m:
            hits.append((int(m.group(1), 16), m.group(2)))
    if not hits:
        fail(f"symbol {name} not found in {cc1}")
    if source_hint:
        for addr, src in hits:
            if source_hint in src:
                return addr, src
        fail(f"symbol {name}: no candidate resolves inside {source_hint} (saw {hits})")
    return hits[0]


def parse_log(text: str) -> dict:
    rec = {"order": [], "funcs": [], "ins": [], "outs": [], "guard_failures": 0,
           "decode_fail": [], "prefs": {}, "stats": {}, "run_error": None}
    for line in text.splitlines():
        if not line.startswith("OA "):
            continue
        body = line[3:]
        if body.startswith("FUNC "):
            parts = body.split()
            rec["funcs"].append({"name": parts[1], "armed": parts[2].endswith("1")})
        elif body.startswith("ORDER "):
            _, n, rest = body.split(" ", 2)
            rec["order"] = [int(x) for x in rest.split(",") if x]
        elif body.startswith("IN "):
            kv = dict(re.findall(r"(\w+)=(-?\d+)", body))
            rec["ins"].append({"num": int(kv.get("num", -1)), "alt": int(kv.get("alt", -1)),
                               "cc": int(kv.get("cc", -1)), "retry": int(kv.get("retry", -1)),
                               "size": int(kv.get("size", -1)), "calls": int(kv.get("calls", -1)),
                               "nrefs": int(kv.get("nrefs", -1)), "freq": int(kv.get("freq", -1)),
                               "live": int(kv.get("live", -1))})
        elif body.startswith("OUT "):
            kv = dict(re.findall(r"(\w+)=(\S+)", body))
            rec["outs"].append({"num": int(re.search(r"OUT (\d+)", body).group(1)),
                                "pseudo": int(kv.get("pseudo", "-1")),
                                "chosen": int(kv.get("chosen", "-1"))})
        elif body.startswith("GUARD-FAILURES"):
            rec["guard_failures"] = int(body.split()[1])
        elif body.startswith("DECODE-FAIL"):
            rec["decode_fail"].append(body)
        elif body.startswith("PREF "):
            kv = dict(re.findall(r"(\w+)=(-?\d+)", body))
            rec["prefs"][body.split()[1]] = int(kv.get("changed", -1))
        elif body.startswith("SETPREF "):
            rec["prefs"]["setpref"] = rec["prefs"].get("setpref", 0) + 1
        elif body.startswith("STATS "):
            kv = dict(re.findall(r"(\w+)=(-?\d+)", body))
            rec["stats"] = {k: int(v) for k, v in kv.items()}
        elif body.startswith("RUN-ERROR"):
            rec["run_error"] = body
    return rec


def parse_dispositions(dump: Path) -> dict[int, int]:
    if not dump.is_file():
        return {}
    text = dump.read_text(encoding="utf-8", errors="replace")
    m = re.search(r";; Register dispositions:\n(.*?)(?:\n\n|\Z)", text, re.S)
    if not m:
        return {}
    return {int(p): int(r) for p, r in re.findall(r"(\d+) in (-?\d+)", m.group(1))}


def run_observer(cc1: Path, src: Path, flags: list[str], includes: list[str],
                 function: str, want_prefs: bool, work: Path, gdb_bin: str) -> dict:
    addrs = {
        "find_reg": resolve_symbol(cc1, "find_reg", "global.c")[0],
        "expand_function_start": resolve_symbol(cc1, "expand_function_start")[0],
    }
    if want_prefs:
        addrs["expand_preferences"] = resolve_symbol(cc1, "expand_preferences")[0]
        addrs["prune_preferences"] = resolve_symbol(cc1, "prune_preferences")[0]
        addrs["set_preference"] = resolve_symbol(cc1, "set_preference")[0]
    sha = subprocess.run([sys.executable, "-c",
                          "import hashlib,sys;print(hashlib.sha256(open(sys.argv[1],'rb').read()).hexdigest())",
                          str(cc1)], capture_output=True, text=True).stdout.strip()
    enforce = sha == PINNED_SHA256
    script = GDB_TEMPLATE
    script = script.replace("__ADDRS__", json.dumps(addrs))
    script = script.replace("__GUARDS__", json.dumps(GUARDS))
    script = script.replace("__ENFORCE__", "True" if enforce else "False")
    script = script.replace("__GATE__", json.dumps(function))
    script = script.replace("__WANT_PREFS__", "True" if want_prefs else "False")
    script = script.replace("__FIRST_PSEUDO__", str(FIRST_PSEUDO))
    gdb_script = work / "observe_alloc.gdb.py"
    gdb_script.write_text(script, encoding="utf-8")

    cmd = [gdb_bin, "--batch", "-q", "-x", str(gdb_script), "--args", str(cc1), "-quiet"]
    cmd += flags
    for inc in includes:
        cmd += ["-I", inc]
    cmd += ["-o", "/dev/null", str(src)]
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=str(Path.cwd()), timeout=900)
    rec = parse_log(proc.stdout + "\n" + proc.stderr)
    rec["cc1"] = str(cc1)
    rec["sha256"] = sha
    rec["pinned"] = enforce
    rec["gdb"] = gdb_bin
    rec["exit"] = proc.returncode
    rec["flags"] = flags
    rec["includes"] = includes

    # The compiler's own answer, for cross-checking.
    dumpbase = work / "cand"
    dcmd = [str(cc1), "-quiet", *flags, "-da", "-dumpbase", str(dumpbase)]
    for inc in includes:
        dcmd += ["-I", inc]
    dcmd += ["-o", "/dev/null", str(src)]
    dump_proc = subprocess.run(dcmd, capture_output=True, text=True, cwd=str(Path.cwd()), timeout=900)
    rec["dump_ok"] = dump_proc.returncode == 0
    disp = parse_dispositions(work / "cand.23.greg")
    rec["dispositions"] = {str(p): r for p, r in sorted(disp.items())}
    return rec


def analyze(rec: dict) -> dict:
    final: dict[int, int] = {}
    for o in rec["outs"]:
        final[o["num"]] = o["chosen"]
    spilled = sorted(num for num, chosen in final.items() if chosen is not None and chosen < 0)
    disp = {int(p): r for p, r in rec.get("dispositions", {}).items()}
    mismatches = []
    for o in rec["outs"]:
        p, chosen = o["pseudo"], o["chosen"]
        if chosen is None:
            continue
        if chosen >= 0 and disp.get(p) != chosen:
            mismatches.append((p, chosen, disp.get(p)))
        if chosen < 0 and p in disp:
            mismatches.append((p, chosen, disp.get(p)))
    rec.update({
        "allocnos": len(final),
        "retry_calls": sum(1 for i in rec["ins"] if i["alt"] == 1),
        "spilled": [{"allocno": n, "pseudo": next((o["pseudo"] for o in rec["outs"] if o["num"] == n), None)}
                    for n in spilled],
        "disposition_count": len(disp),
        "mismatches": mismatches,
    })
    return rec


def report_human(rec: dict, verbose: bool) -> None:
    print(f"cc1: {rec['cc1']}")
    print(f"sha256: {rec['sha256']} ({'pinned' if rec['pinned'] else 'unpinned: entry guards skipped'})")
    print(f"gdb: {rec['gdb']}  flags: {' '.join(rec['flags'])}")
    funcs = [f["name"] for f in rec["funcs"] if f["armed"]]
    print(f"function: {', '.join(funcs) if funcs else '(none armed)'}")
    print(f"allocno_order: {len(rec['order'])}")
    print(f"find_reg: {len(rec['ins'])} calls / {rec['allocnos']} allocnos / {rec['retry_calls']} retries (alt=1)")
    if rec["spilled"]:
        print("no register (spilled): " + ", ".join(
            f"{s['allocno']}(pseudo {s['pseudo']})" for s in rec["spilled"]))
    else:
        print("no register (spilled): none")
    if rec["dump_ok"]:
        print(f"dispositions: {rec['disposition_count']} (compiler dump) / mismatches: {len(rec['mismatches'])}")
        for p, chosen, dumped in rec["mismatches"][:5]:
            print(f"  mismatch: pseudo {p} chosen {chosen} dump {dumped}")
    else:
        print("dispositions: dump not produced (cross-check skipped)")
    if rec.get("prefs"):
        parts = ", ".join(f"{k}={v}" for k, v in rec["prefs"].items())
        print(f"preference edits: {parts}")
    if verbose and rec["order"]:
        print("order: " + " ".join(map(str, rec["order"][:40])) + (" ..." if len(rec["order"]) > 40 else ""))
    if rec["guard_failures"]:
        print(f"GUARD FAILURES: {rec['guard_failures']} -- the trace is invalid")
    if rec["decode_fail"]:
        print(f"decode failures: {len(rec['decode_fail'])} -- the trace is invalid")


def selftest(work: Path, gdb_bin: str) -> int:
    cc1 = DEFAULT_CC1
    if not cc1.is_file():
        print(f"selftest: skipped (no cc1 at {cc1})")
        return 0
    src = work / "selftest_alloc.c"
    decl = "\n".join(f"    int v{i} = p[{i}];" for i in range(12))
    calls = "\n".join(f"    s += sink(v{i});" for i in range(12))
    total = " + ".join(f"v{i}" for i in range(12))
    src.write_text(
        "extern int sink(int);\n"
        "int demo(int *p, int n) {\n"
        f"{decl}\n"
        "    int s = n;\n"
        f"{calls}\n"
        f"    return s + {total};\n"
        "}\n", encoding="utf-8")
    rec = analyze(run_observer(cc1, src, ["-O2", "-G0"], [], "demo", True, work, gdb_bin))
    checks = 0

    def ck(name: str, ok: bool, detail: str = "") -> None:
        nonlocal checks
        checks += 1
        if not ok:
            print(f"selftest: FAIL {name} {detail}")
            raise SystemExit(1)

    print("selftest: fixture demo() compiled at -O2 -G0")
    ck("gdb ran", rec["exit"] == 0, f"exit {rec['exit']}")
    ck("entry guards", rec["guard_failures"] == 0, f"{rec['guard_failures']} failures")
    ck("decode", not rec["decode_fail"], str(rec["decode_fail"][:2]))
    ck("order read", len(rec["order"]) > 0, "empty allocno_order")
    ck("find_reg calls", len(rec["ins"]) > 0, "no find_reg call recorded")
    ck("allocnos seen", rec["allocnos"] > 0, "no allocno decision recorded")
    ck("dispositions", rec["disposition_count"] > 0, "compiler dump had no dispositions")
    ck("chosen == dispositions", not rec["mismatches"], str(rec["mismatches"][:3]))
    ck("order covers allocnos", len(rec["order"]) == len({i["num"] for i in rec["ins"]}) or
       len(rec["order"]) >= rec["allocnos"], "order shorter than attempted allocnos")
    ck("preference phases fired", "expand_preferences" in rec.get("prefs", {}) and
       "prune_preferences" in rec.get("prefs", {}), str(rec.get("prefs", {})))
    print(f"selftest: pass ({checks} checks)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Observe the shipped cc1's global allocation decisions (read-only)")
    ap.add_argument("--cc1", default=str(DEFAULT_CC1), help="path to the shipped cc1")
    ap.add_argument("--src", help="C source to compile")
    ap.add_argument("--flags", default="-O2 -G0", help="compiler flags (default: -O2 -G0)")
    ap.add_argument("--include", action="append", default=[], help="include directory (repeatable)")
    ap.add_argument("--function", default="", help="only record this function (default: first function)")
    ap.add_argument("--prefs", action="store_true", help="also observe expand/prune preference edits")
    ap.add_argument("--json", action="store_true", help="emit JSON instead of a table")
    ap.add_argument("--verbose", action="store_true", help="print the head of the allocation order")
    ap.add_argument("--work", help="scratch directory (default: a temp dir)")
    ap.add_argument("--selftest", action="store_true", help="run the synthetic fixture and assert the invariants")
    args = ap.parse_args()

    if not shutil.which("gdb"):
        print("error: gdb not found on PATH (the observer needs gdb)", file=sys.stderr)
        return 2
    gdb_bin = shutil.which("gdb") or "gdb"
    cc1 = Path(args.cc1).expanduser()
    if not cc1.is_file():
        fail(f"cc1 not found: {cc1}")

    tmp = None
    if args.work:
        work = Path(args.work).expanduser()
        work.mkdir(parents=True, exist_ok=True)
    else:
        tmp = tempfile.TemporaryDirectory(prefix="observe-alloc-")
        work = Path(tmp.name)

    if args.selftest:
        return selftest(work, gdb_bin)
    if not args.src:
        fail("--src is required (or use --selftest)")
    src = Path(args.src).expanduser().resolve()
    if not src.is_file():
        fail(f"source not found: {src}")
    flags = shlex.split(args.flags)
    rec = analyze(run_observer(cc1, src, flags, args.include, args.function, args.prefs, work, gdb_bin))
    if args.json:
        print(json.dumps(rec, indent=2, ensure_ascii=False))
    else:
        report_human(rec, args.verbose)
    bad = rec["guard_failures"] or rec["decode_fail"] or rec["mismatches"]
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
